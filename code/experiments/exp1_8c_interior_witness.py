"""Exp 1.8c — the interior witness block G_WW on the production BlockViT-v2.

Astra's math_01.md poses a sharp, measurable question about P3:

  * Lemma 3.1 / eq (3.1)-(3.2): an interior layer a_n = W h_n + b gives the
    lower bound  lambda_max(G_phiphi) >= lambda_max(G_WW) >= lambda_max(S_h,a),
    so a *fixed-width* downstream bottleneck does not stop a width-linear
    curvature floor generated by an interior layer.
  * eq (3.3) is the universally valid version: the witness energy must be
    pushed through the ACTUAL downstream Jacobian, including normalization
    and spatial mixing.
  * Counterexample 3.4: train-mode BatchNorm placed immediately after
    W h_n can erase the whole witness. In the degenerate constant-feature
    case G_WW = 0 exactly while S_h still has an eigenvalue proportional to
    the width M.

BlockViT-v2 has exactly this structure. Its segmentation head is

    seg_head = [ Conv2d(M+K -> 96, 3x3), BatchNorm2d(96), ReLU,
                 Conv2d(96 -> 48, 3x3),  BatchNorm2d(48), ReLU,
                 Conv2d(48 -> 4, 3x3) ]

fed by  fused = cat([upsampled (M channels), feat_2d (K=64 channels)], 1).
seg_head[0] is the ONLY Theta(M)-input layer in the whole downstream path
(the transformer is M-wide but its blocks are M x M, not M-in/fixed-out),
and it is followed immediately by a BatchNorm. It is therefore the exact
production instance of Lemma 3.1's W, with Counterexample 3.4's BN sitting
in the one place that can kill it.

What this script measures, at RANDOM INIT, on ONE real breast fold-0 core
(the densest core batch exp1_8 uses), for widths M and seeds:

    lam_WW    lambda_max of the GGN block restricted to seg_head[0].weight
    lam_Wb    same, weight + bias together
    lam_Sh    lambda_max of the incoming per-pixel feature Gram
              S_h = (1/N) sum_n h_n h_n^T over valid pixels, h_n in R^{M+K}
    lam_Sh9   the conv-correct version: h_n is the 3x3 patch, in R^{9(M+K)},
              since seg_head[0] is a 3x3 conv and its unit-Frobenius witness
              lives in R^{96 x 9(M+K)}
    lam_phi   lambda_max of the FULL spatial block (exp1_8's quantity)

in three BN modes:

    train      model.train()  -- BN uses batch statistics, i.e. what the
               optimizer actually sees at step 0 (exp1_8's protocol)
    eval       model.eval()   -- BN uses running stats, which at init are
               (mean 0, var 1), i.e. an affine identity
    eval_head  model.train() everywhere EXCEPT the seg_head BatchNorms,
               which are put in eval. This is the clean isolation: the
               spectral module's own BatchNorms (wn_norm, norm) keep batch
               statistics so the incoming features h_n are IDENTICAL to
               train mode, and the only thing that changes is the
               normalization sitting on top of the witness layer.

Full `eval` is reported because it was asked for, but it is confounded:
turning off wn_norm's batch statistics de-standardizes the raw spectra and
changes h_n itself. Read `eval_head` for the mechanism.

Usage:
    python code/experiments/exp1_8c_interior_witness.py \
        --widths 48 192 384 --seeds 0 1
"""
