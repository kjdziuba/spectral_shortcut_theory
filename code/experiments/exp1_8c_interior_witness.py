def freeze_bn_running_stats(model: nn.Module) -> None:
    """Keep batch statistics but stop running-stat drift across the sweep.

    With momentum=0 the update running <- (1-m)*running + m*batch is a no-op,
    so the running estimates stay at their init values (mean 0, var 1) no
    matter how many measurement forwards we run. That is what makes the
    `eval` arm an honest "BN = affine identity" arm.
    """
    for m in model.modules():
        if isinstance(m, (nn.BatchNorm1d, nn.BatchNorm2d)):
            m.momentum = 0.0


def build_model(width: int, seed: int, args) -> nn.Module:
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    model = BlockViTv2(
        in_channels=3, num_classes=args.num_classes, num_spectral=args.num_spectral,
        reduce_dim=args.reduce_dim, patch_tok_size=args.patch_tok_size,
        hidden_dim=width, num_layers=args.num_layers, num_heads=args.num_heads,
        mlp_ratio=4.0, dropout=0.0, spatial_size=args.spatial_size,
        spectral_norm=not getattr(args, "no_spectral_norm", False),
    ).to(args.device)
    model.train()
    freeze_bn_running_stats(model)
    return model


def set_bn_mode(model: nn.Module, mode: str) -> None:
    """Put the model in one of the three BN regimes described in the docstring."""
    if mode == "train":
        model.train()
    elif mode == "eval":
        model.eval()
    elif mode == "eval_head":
        model.train()
        for m in model.seg_head.modules():
            if isinstance(m, nn.modules.batchnorm._BatchNorm):
                m.eval()
    else:
        raise ValueError(f"unknown BN mode: {mode}")


def split_params(model: nn.Module):
    """Theory's two modules: f_theta = spectral_reduce, g_phi = everything else."""
    theta, phi = [], []
    for name, p in model.named_parameters():
        (theta if name.startswith("spectral_reduce") else phi).append(p)
    return theta, phi


