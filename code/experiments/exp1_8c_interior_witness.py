def load_densest_batch(args):
    """Reproduce exp1_8's batch 0: the densest of the first 24 train cores."""
    split_file = Path(args.data_dir) / f"splits_fold{args.fold}.json"
    if not split_file.exists():
        raise SystemExit(f"missing split file: {split_file}")

    full_split = json.loads(split_file.read_text())
    # exp1_8 defaults: n_batches=4, batch_size=1, core_oversample=6 -> 24 names.
    core_names = full_split[args.split][: args.n_candidate_cores]
    trimmed = {k: (core_names if k == args.split else []) for k in full_split}
    tmp_split = Path(args.tmp_dir) / f"_split1_8c_{args.dataset_name}_f{args.fold}.json"
    tmp_split.parent.mkdir(parents=True, exist_ok=True)
    tmp_split.write_text(json.dumps(trimmed))
    print(f"[data] candidate cores ({len(core_names)}): {core_names}", flush=True)

    ds = CoreDataset(
        data_dir=args.data_dir, split_file=str(tmp_split), split=args.split,
        spatial_size=args.spatial_size, augment=False,
    )
    scored = []
    for i in range(len(ds)):
        _, y = ds[i]
        scored.append((int((torch.as_tensor(y) != 255).sum().item()), i))
    scored.sort(reverse=True)
    if not scored or scored[0][0] == 0:
        raise SystemExit("no usable cores (all pixels ignored)")
    n_valid, idx = scored[0]
    core_name = core_names[idx] if idx < len(core_names) else f"idx{idx}"

    x, y = ds[idx]
    X = torch.as_tensor(x).float().unsqueeze(0).to(args.device)
    Y = torch.as_tensor(y).long().unsqueeze(0).to(args.device)
    n_valid = int((Y != 255).sum().item())
    print(f"[data] densest core: {core_name} (ds index {idx}), "
          f"{n_valid} valid px ({n_valid / Y[0].numel():.1%}), X {tuple(X.shape)}",
          flush=True)
    del ds
    return X, Y, n_valid, core_name


# --------------------------------------------------------------------------
# incoming-feature Gram S_h
# --------------------------------------------------------------------------
def _gram_eig(vecs: torch.Tensor, prefix: str, chunk: int = 4096) -> dict:
    """Spectrum of S = (1/N) V^T V and of its mean-centred version, in float64.

    The centred Gram matters because it is EXACTLY what train-mode BN leaves
    of a Lemma-3.1 witness. For the witness Delta W = a u^T the pre-activation
    perturbation is (h_n^T u) a, a scalar field over sites; BN immediately
    subtracts that field's site mean, so the surviving witness energy is
    governed by  S_cen = (1/N) sum (h_n - mu)(h_n - mu)^T = S - mu mu^T,
    not by S. Counterexample 3.4 is the extreme case S_cen = 0 while S != 0.

    ``cos_u_mu`` is the alignment between S's top eigenvector and the mean
    feature direction: near 1 means the S-maximising witness is precisely the
    one BN annihilates.
    """
    N, D = vecs.shape
    S = torch.zeros(D, D, dtype=torch.float64, device=vecs.device)
    mu = torch.zeros(D, dtype=torch.float64, device=vecs.device)
    for i in range(0, N, chunk):
        c = vecs[i: i + chunk].double()
        S += c.T @ c
        mu += c.sum(0)
    S /= N
    mu /= N

    ev, evec = torch.linalg.eigh(S)
    lam = float(ev[-1].item())
    tr = float(S.diagonal().sum().item())
    u = evec[:, -1]

    S_cen = S - torch.outer(mu, mu)
    lam_c = float(torch.linalg.eigvalsh(S_cen)[-1].item())
    tr_c = float(S_cen.diagonal().sum().item())

    mu_n = float(mu.norm().item())
    return {
        f"lam_{prefix}": lam,
        f"trace_{prefix}": tr,
        f"eff_rank_{prefix}": tr / lam if lam > 0 else float("nan"),
        f"lam_{prefix}_cen": lam_c,
        f"trace_{prefix}_cen": tr_c,
        f"cen_frac_{prefix}": lam_c / lam if lam > 0 else float("nan"),
        f"cos_u_mu_{prefix}": float((u @ mu).abs().item()) / mu_n if mu_n > 0 else float("nan"),
        f"dim_{prefix}": D,
    }


def fused_gram_stats(fused: torch.Tensor, Y: torch.Tensor, n_up: int,
                     want_patch: bool = True) -> dict:
    """Gram statistics of the features entering seg_head[0], valid pixels only.

    Versions computed:
      * Sh    per-pixel  h_n in R^{M+K}     -- Lemma 3.1 read literally
      * Sh9   3x3 patch  h_n in R^{9(M+K)}  -- the conv-correct incoming vector,
              since seg_head[0]'s weight really acts on the unfolded patch
      * Shup  the M upsampled (transformer) channels only  -- the ONLY part of
              h_n whose dimension grows with the width
      * Shsk  the K=64 skip channels only (feat_2d) -- width-independent

    The up/skip split is the decisive one for Theorem 3.2's hypothesis
    lambda_max(S_h) >= a_0 M: only the up-block can supply width growth.
    """
    B, C, H, W = fused.shape
    keep = (Y != 255).reshape(-1)
    out = {}
    with torch.no_grad():
        hv = fused.permute(0, 2, 3, 1).reshape(-1, C)[keep]
        out.update(_gram_eig(hv, "Sh"))
        out.update(_gram_eig(hv[:, :n_up], "Shup"))
        out.update(_gram_eig(hv[:, n_up:], "Shsk"))
        del hv
        if want_patch:
            U = F.unfold(fused, kernel_size=3, padding=1)          # (B, C*9, HW)
            U = U.permute(0, 2, 1).reshape(-1, C * 9)[keep]
            out.update(_gram_eig(U, "Sh9"))
            del U
    torch.cuda.empty_cache()
    return out


def capture_head_activations(model: nn.Module, X: torch.Tensor):
    """One forward pass; grab seg_head input, post-conv, post-BN, and logits.

    These are Astra's requested witness diagnostics: incoming energy,
    post-BN energy, and the softmax weighting that multiplies them.
    """
    store = {}

    # NOTE: seg_head[2] is nn.ReLU(inplace=True), which overwrites the tensor
    # seg_head[1] returned. Clone in the hooks or "post-BN energy" silently
    # becomes post-ReLU energy (~half of it).
    def pre_hook(mod, inp):
        store["fused"] = inp[0].detach().clone()

    def conv_hook(mod, inp, out):
        store["a"] = out.detach().clone()

    def bn_hook(mod, inp, out):
        store["bn"] = out.detach().clone()

    hs = [
        model.seg_head.register_forward_pre_hook(pre_hook),
        model.seg_head[0].register_forward_hook(conv_hook),
        model.seg_head[1].register_forward_hook(bn_hook),
    ]
    try:
        with torch.no_grad(), math_attention():
            logits = model(X).detach()
    finally:
        for h in hs:
            h.remove()
    return store["fused"], store["a"], store["bn"], logits


def softmax_stats(logits: torch.Tensor, Y: torch.Tensor):
    with torch.no_grad():
        keep = (Y != 255)
        p = torch.softmax(logits, dim=1)
        pmin = p.min(dim=1).values[keep]
        lg = logits.permute(0, 2, 3, 1)[keep]
        return dict(
            p_min_mean=float(pmin.mean().item()),
            p_min_min=float(pmin.min().item()),
            logit_absmax=float(lg.abs().max().item()),
            logit_std=float(lg.std().item()),
        )


# --------------------------------------------------------------------------
def loglog_slope(widths, values):
    w = np.asarray(widths, dtype=float)
    v = np.asarray(values, dtype=float)
    ok = np.isfinite(v) & (v > 0)
    if ok.sum() < 2:
        return float("nan")
    return float(np.polyfit(np.log(w[ok]), np.log(v[ok]), 1)[0])


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data_dir", default="/mnt/hdd2/u37314kd/data_breast_v2_pca23")
    ap.add_argument("--dataset_name", default="breast")
    ap.add_argument("--fold", type=int, default=0)
    ap.add_argument("--split", default="train")
    ap.add_argument("--widths", type=int, nargs="+", default=[48, 192, 384])
    ap.add_argument("--seeds", type=int, nargs="+", default=[0, 1])
    ap.add_argument("--modes", nargs="+", default=["train", "eval_head", "eval"])
    ap.add_argument("--n_candidate_cores", type=int, default=24,
                    help="load this many cores, measure only the densest "
                         "(24 reproduces exp1_8's batch 0)")
    ap.add_argument("--n_iter", type=int, default=100, help="power iterations, small blocks")
    ap.add_argument("--n_iter_phi", type=int, default=25, help="power iterations, phi block")
    ap.add_argument("--tol", type=float, default=1e-5)
    ap.add_argument("--tol_phi", type=float, default=1e-4)
    ap.add_argument("--spatial_size", type=int, default=336)
    ap.add_argument("--reduce_dim", type=int, default=64)
    ap.add_argument("--num_spectral", type=int, default=314)
    ap.add_argument("--num_classes", type=int, default=4)
    ap.add_argument("--num_layers", type=int, default=12)
    ap.add_argument("--num_heads", type=int, default=12)
    ap.add_argument("--patch_tok_size", type=int, default=16)
    ap.add_argument("--device", default="cuda")
    ap.add_argument("--no_spectral_norm", action="store_true")
    ap.add_argument("--no_phi", action="store_true", help="skip the expensive full-phi block")
    ap.add_argument("--no_patch_gram", action="store_true")
    ap.add_argument("--tmp_dir", default="/tmp/claude-1008/spectral_shortcut_scratch")
    ap.add_argument("--out", default=str(THEORY_ROOT / "results" / "exp1_8c_interior_witness.csv"))
    args = ap.parse_args()

    for w in args.widths:
        if w % args.num_heads != 0:
            raise SystemExit(f"width {w} not divisible by num_heads {args.num_heads}")

    X, Y, n_valid, core_name = load_densest_batch(args)

    rows = []
    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    for width in args.widths:
        for seed in args.seeds:
            model = build_model(width, seed, args)
            theta, phi = split_params(model)
            W0 = model.seg_head[0].weight
            b0 = model.seg_head[0].bias
            head_in = width + args.reduce_dim

            for mode in args.modes:
                set_bn_mode(model, mode)
                t0 = time.time()
                torch.cuda.reset_peak_memory_stats()

                # --- (b) incoming feature Gram + witness diagnostics ---------
                fused, a_pre, a_bn, logits = capture_head_activations(model, X)
                gs = fused_gram_stats(fused, Y, n_up=width,
                                      want_patch=not args.no_patch_gram)
                keep = (Y != 255)
                with torch.no_grad():
                    e_in = float((fused.permute(0, 2, 3, 1)[keep] ** 2).sum(-1).mean().item())
                    e_pre = float((a_pre.permute(0, 2, 3, 1)[keep] ** 2).sum(-1).mean().item())
                    e_bn = float((a_bn.permute(0, 2, 3, 1)[keep] ** 2).sum(-1).mean().item())
                    bn_gain = float(np.sqrt(e_bn / e_pre)) if e_pre > 0 else float("nan")
                sm = softmax_stats(logits, Y)
                del fused, a_pre, a_bn, logits
                torch.cuda.empty_cache()

                # --- (a) interior witness block G_WW -------------------------
                lam_WW = top_eigenvalue_ggn_block(
                    model, X, Y, [W0], n_iter=args.n_iter, tol=args.tol, seed=seed
                )
                lam_Wb = top_eigenvalue_ggn_block(
                    model, X, Y, [W0, b0], n_iter=args.n_iter, tol=args.tol, seed=seed
                )

                # --- (c) full phi block, for reference ------------------------
                lam_phi = float("nan")
                if not args.no_phi:
                    lam_phi = top_eigenvalue_ggn_block(
                        model, X, Y, phi, n_iter=args.n_iter_phi, tol=args.tol_phi, seed=seed
                    )

                peak = torch.cuda.max_memory_allocated() / 1e9
                rows.append(dict(
                    dataset=args.dataset_name, fold=args.fold, split=args.split,
                    core=core_name, n_valid_px=n_valid,
                    width=width, seed=seed, mode=mode,
                    head_in=head_in, n_params_W=W0.numel(), n_params_b=b0.numel(),
                    lam_WW=lam_WW, lam_Wb=lam_Wb, lam_phi=lam_phi,
                    ratio_WW_Sh=lam_WW / gs["lam_Sh"] if gs["lam_Sh"] > 0 else float("nan"),
                    ratio_WW_Sh9=(lam_WW / gs["lam_Sh9"]
                                  if gs.get("lam_Sh9", 0) > 0 else float("nan")),
                    ratio_WW_phi=lam_WW / lam_phi if lam_phi and lam_phi > 0 else float("nan"),
                    energy_in=e_in, energy_preBN=e_pre, energy_postBN=e_bn,
                    bn_gain_rms=bn_gain,
                    **gs, **sm,
                    reduce_dim=args.reduce_dim, spatial_size=args.spatial_size,
                    peak_gb=peak, secs=time.time() - t0,
                ))
                print(f"  M={width:4d} seed={seed} {mode:9s} | "
                      f"lam_WW={lam_WW:.4e} lam_Wb={lam_Wb:.4e} "
                      f"lam_Sh={gs['lam_Sh']:.4e} lam_phi={lam_phi:.4e} | "
                      f"WW/Sh={rows[-1]['ratio_WW_Sh']:.3e} "
                      f"bn_gain={bn_gain:.3e} p_min={sm['p_min_mean']:.3e} | "
                      f"{peak:.1f}GB {time.time()-t0:.0f}s", flush=True)
                pd.DataFrame(rows).to_csv(out_path, index=False)

            del model, theta, phi, W0, b0
            torch.cuda.empty_cache()

    df = pd.DataFrame(rows)
    df.to_csv(out_path, index=False)
    print(f"\n[write] {out_path}  ({len(df)} rows)")

    # ---- summary table + log-log slopes -----------------------------------
    cols = ["lam_WW", "lam_Wb", "lam_phi",
            "lam_Sh", "lam_Sh_cen", "lam_Sh9", "lam_Shup", "lam_Shsk",
            "cos_u_mu_Sh", "ratio_WW_Sh", "bn_gain_rms", "p_min_mean"]
    cols = [c for c in cols if c in df.columns]
    g = df.groupby(["mode", "width"])[cols].mean().reset_index()
    print("\n" + g.to_string(index=False, float_format=lambda v: f"{v:.4g}"))

    slopes = {}
    print("\nlog-log slopes vs M:")
    for mode in df["mode"].unique():
        sub = g[g["mode"] == mode]
        slopes[mode] = {c: loglog_slope(sub["width"], sub[c]) for c in cols}
        line = "  ".join(f"{c}={slopes[mode][c]:+.3f}" for c in cols)
        print(f"  {mode:9s}  {line}")

    sp = out_path.with_suffix(".summary.json")
    sp.write_text(json.dumps({
        "dataset": args.dataset_name, "fold": args.fold, "core": core_name,
        "n_valid_px": n_valid, "widths": args.widths, "seeds": args.seeds,
        "modes": args.modes, "reduce_dim": args.reduce_dim,
        "per_mode_width": g.to_dict(orient="records"),
        "loglog_slopes_vs_M": slopes,
    }, indent=2))
    print(f"[write] {sp}")


if __name__ == "__main__":
    main()
